package com.thelongtravail.client;

import com.thelongtravail.TravailAspect;

/** 保留作者设定的换行和标点。 */
public final class DiaryPageProse {
    private DiaryPageProse() {}

    public static String text(TravailAspect aspect, boolean witness) {
        String prose = switch (aspect) {
            case FLOURISHING -> witness ? """
                    夏花锦绣，
                    如波浪般摇曳，
                    （玩家名）张开手臂，
                    香风满袖。

                    逢魔之时，萤火浮起，
                    虫声铺天盖地。
                    稍感疲累的（玩家名），
                    沉入地面的群星中。
                    """ : """
                    阳光如碎金落下。
                    （玩家名）抬手接过，
                    突兀间看见指缝中闪过的一线目光。
                    风吹草浪，姹紫嫣红。

                    “真安静啊……”
                    明明总是有悉悉索索的声音，
                    （玩家名）如是说道。
                    他加快脚步。
                    """;
            case ABYSS -> witness ? """
                    在风与水的尽头，
                    晨昏齐悬天际。
                    伫立于此，无论倾诉什么，
                    涛声都将回应。

                    海是时间的一种辽阔，
                    如梦幻泡影。
                    倒映着的月光，
                    朝（玩家名）奔赴而来。
                    """ : """
                    如星空般的深蓝啊，
                    广袤、仁慈、威严、幽邃。

                    群星已达正位；
                    （玩家名）听见了血脉相连的低语。
                    坠落吧，坠落吧，坠落吧……

                    海是万物的源泉，
                    因此而回归母胎。
                    """;
            case FAR_REACH -> witness ? """
                    夕日流金，天光澄澈。
                    “我来自遥远的地方……”

                    烈日长照黄金之野，
                    万物灼灼，
                    传说从此启程。

                    （玩家名）行于其间，
                    行走于个体的荒原。
                    """ : """
                    人是时间里的旅行者，
                    偶然走过彼此的片刻。

                    风雨不绝于耳，
                    前有无光之夜，
                    所以执火而行，摇光照亮一隅。

                    旷野漫漫，
                    孤身行于荒原。
                    """;
            case DEEP_VALLEY -> witness ? """
                    （玩家名）沿谷径向前，
                    身在幽深之处向上望去，
                    看见雾气、苔痕、蛛丝，
                    共映出不可及的高天。

                    回响的呓语不知何时沉默，
                    无人知晓的故事，
                    在水洼轻轻晕开。
                    有无垢之物，
                    沿着溪流缓慢流淌。
                    """ : """
                    日轮在上，月影在下，
                    谷底摇摇晃晃，
                    像是谁遗落的摇篮。

                    来吧，来吧，再往下一点。
                    声音会变得很近，
                    名字也会变得一样。

                    此岸也好，彼世也罢，
                    你也是这里的人吗？
                    """;
            case UNDERWORLD -> witness ? """
                    昨夜，
                    有人在土中埋下了一只乌鸦。
                    （玩家名）俯身看了很久。

                    风掠过它的旧名，
                    把一切轻轻带走。
                    永不复返，永不复返。

                    冥府的道路向下延伸，
                    白色死神在尽头微笑。
                    """ : """
                    恶火在地下长明，
                    灰烬于尘世上升。

                    谁在呼唤，谁在应答，
                    血光照彻焦土，
                    熔岩缓慢流淌，

                    （玩家名）走过炽热的脉搏，
                    闯入无门的冥府。
                    """;
            case BOUNDLESS -> witness ? """
                    平凡的日子被远远留在身后，
                    曾经坠落的天空，
                    在虚无中缓慢盛放。

                    黑暗交错如藤，
                    牵住脚步，指引前路。
                    （玩家名）走入那扇门后，
                    成为空空世界的独一无二。
                    """ : """
                    梦走在梦中，天悬于天外。
                    末路，末路，再向前走一点。

                    （玩家名）记叙着虚空的混沌，
                    攥写无形无相之物。
                    荒原浮在群星之四方，
                    沉睡在宏大的寂静里。
                    """;
        };
        return prose.strip().replace("（玩家名）", "旅人");
    }
}
